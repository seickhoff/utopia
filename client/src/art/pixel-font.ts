const LIT = "#";
const BLANK = GLYPHS[" "];

/** The characters the font can draw. */
export const FONT_CHARACTERS: readonly string[] = Object.keys(GLYPHS);

/** A character's rows as bits, the leftmost pixel in bit 7; unknown characters draw blank. */
export function glyphRows(character: string): number[] {
  const glyph = GLYPHS[character.toUpperCase()] ?? BLANK;
  return glyph
    .split("/")
    .map((row) => [...row].reduce((bits, pixel) => (bits << 1) | (pixel === LIT ? 1 : 0), 0));
}
